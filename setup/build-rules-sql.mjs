// Writes worker/migrations/0002_rules.sql: the score cards (from worker/src/cards.js) and the hearing journals
// and book list (from setup/data/journals.json) as D1 tables, which the schedule copies to the Rules sheet.
//   node setup/build-rules-sql.mjs
import fs from 'node:fs';
import { CARDS, CATEGORIES, RULES_VERSION } from '../worker/src/cards.js';
import J from './data/journals.json' with { type: 'json' };

const sq = v => (v === null || v === undefined ? "''" : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const ins = (tbl, cols, rows) => rows.map(r => `INSERT INTO ${tbl} (${cols.map(c => `"${c}"`).join(', ')}) VALUES (${r.map(sq).join(', ')});`);
const sql = [
  '-- Phase 2: score cards, Seva rules, hearing journals and books (generated by setup/build-rules-sql.mjs; do not edit by hand)',
  `CREATE TABLE card_ranges ("card" TEXT NOT NULL, "category" TEXT NOT NULL, "order" INTEGER NOT NULL, "label" TEXT NOT NULL, "from" TEXT NOT NULL DEFAULT '', "to" TEXT NOT NULL DEFAULT '', "marks" INTEGER NOT NULL, "version" TEXT NOT NULL, PRIMARY KEY ("card", "category", "order"));`,
  `CREATE TABLE seva_rules ("card" TEXT NOT NULL, "rule" TEXT NOT NULL, "value" TEXT NOT NULL, "score" INTEGER NOT NULL DEFAULT 0, "note" TEXT NOT NULL DEFAULT '', "version" TEXT NOT NULL);`,
  `CREATE TABLE chetna_options ("kind" TEXT NOT NULL CHECK ("kind" IN ('POSITIVE','NEGATIVE')), "option" TEXT NOT NULL, "order" INTEGER NOT NULL, "active" INTEGER NOT NULL DEFAULT 1, PRIMARY KEY ("kind", "option"));`,
  `CREATE TABLE lectures ("lecture_id" TEXT PRIMARY KEY, "journal" TEXT NOT NULL, "week" INTEGER NOT NULL, "slot" TEXT NOT NULL, "title" TEXT NOT NULL, "audio_url" TEXT NOT NULL DEFAULT '', "order" INTEGER NOT NULL);`,
  `CREATE INDEX lectures_by_journal ON lectures ("journal", "order");`,
  `CREATE TABLE books ("book_id" TEXT PRIMARY KEY, "title" TEXT NOT NULL, "level" TEXT NOT NULL, "words" INTEGER, "language" TEXT NOT NULL DEFAULT '', "order" INTEGER NOT NULL, "link" TEXT NOT NULL DEFAULT '');`
];
const ranges = [];
// the Excel (step) cards only: the linear TRD card (Phase 22) has two points per item, not option tables — 0002 stays as built
const STEP_CARDS = Object.entries(CARDS).filter(([, def]) => def.kind !== 'linear');
for (const [card, def] of STEP_CARDS) for (const c of CATEGORIES) def[c].forEach((o, i) =>
  ranges.push([card, c, i + 1, o.label, o.from ?? (o.min ?? ''), o.to ?? (o.max ?? ''), o.marks, RULES_VERSION]));
sql.push(...ins('card_ranges', ['card', 'category', 'order', 'label', 'from', 'to', 'marks', 'version'], ranges));
const seva = [];
for (const [card, def] of STEP_CARDS) {
  if (def.seva.rule === 'divide') seva.push([card, 'divide', String(def.seva.by), 0, `week's minutes ÷ ${def.seva.by} × 100, capped at 100`, RULES_VERSION]);
  else { for (const [below, score] of def.seva.steps) seva.push([card, 'step', `below ${below}`, score, '', RULES_VERSION]);
         seva.push([card, 'step', 'otherwise', def.seva.top, '', RULES_VERSION]); }
}
sql.push(...ins('seva_rules', ['card', 'rule', 'value', 'score', 'note', 'version'], seva));
const order = { 'SPS/DPS': 0, BSS: 1, BVS: 2 }, slot = { SPL: 1, GKGML: 2, 'LOW 1': 3, 'LOW 2': 4 };
sql.push(...ins('lectures', ['lecture_id', 'journal', 'week', 'slot', 'title', 'audio_url', 'order'],
  J.lectures.map(l => [l.lecture_id, l.journal, l.week, l.slot, l.title, l.audio_url, l.week * 10 + slot[l.slot]])));
sql.push(...ins('books', ['book_id', 'title', 'level', 'words', 'language', 'order', 'link'],
  J.books.map(b => [b.book_id, b.title, b.level, b.words, b.language, b.order, J.book_link])));
sql.push(
  "UPDATE batches SET hearing_journal = 'SPS/DPS' WHERE hearing_journal = 'Level 4';",
  "UPDATE batches SET hearing_journal = 'BSS' WHERE hearing_journal = 'Level 5 BSS';",
  "UPDATE batches SET hearing_journal = 'BVS' WHERE hearing_journal = 'Level 5 BVS';",
  `UPDATE settings SET value = '${RULES_VERSION}', changed_by = 'phase 2' WHERE key = 'rules_version';`,
  "UPDATE settings SET value = 'j1', changed_by = 'phase 2' WHERE key = 'journals_version';",
  "INSERT INTO mirror_state (tbl) VALUES ('card_ranges'), ('seva_rules'), ('chetna_options'), ('lectures'), ('books');",
  "UPDATE mirror_state SET dirty = dirty + 1 WHERE tbl IN ('batches', 'settings');"
);
const out = new URL('../worker/migrations/0002_rules.sql', import.meta.url);
fs.writeFileSync(out, sql.join('\n') + '\n');
console.log(`wrote ${out.pathname.split('/').slice(-2).join('/')}: ${ranges.length} card options, ${seva.length} Seva rules, ${J.lectures.length} lectures, ${J.books.length} books`);
