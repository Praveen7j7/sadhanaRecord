// The change-log triggers for copying the changing tables to Sheets row by row (worker/src/mirror.js), one set per
// table in worker/src/mirrorkeys.js › KEYED. 0018 was the first form; 0022 the full current form (all tables then).
//   node setup/build-mirror-sql.mjs                         → 0022_mirror_log.sql (the full form; already applied)
//   node setup/build-mirror-sql.mjs 0024_mirror_leaders leaders   → a NEW migration with only the named tables' triggers
//                                                             (each copied whole once, then live)
import { writeFileSync } from 'node:fs';
import { KEYED, LOG_WHEN } from '../worker/src/mirrorkeys.js';
// every mirror trigger reads the Sheets copy switch (migration 0075): while the copy is paused a change queues nothing
import { COPY_ON } from '../worker/src/mirror.js';
const guard = (c) => (c ? `(${c}) AND ${COPY_ON}` : COPY_ON);

const [outName, ...only] = process.argv.slice(2);
if (outName) {
  // delta: triggers for tables added to KEYED since the last migration
  const col = (c) => `"${c}"`, lines = [`-- Copy to Sheets: triggers for ${only.join(', ')} (generated by setup/build-mirror-sql.mjs; see 0022 for the design).`];
  for (const t of only) {
    if (!KEYED[t]) throw new Error('not in KEYED: ' + t);
    const [a, b] = KEYED[t], k2 = (row) => (b ? `${row}.${col(b)}` : "''");
    const ins = (row) => `INSERT INTO mirror_log (tbl, k1, k2) VALUES ('${t}', ${row}.${col(a)}, ${k2(row)});`;
    const moved = b ? `OLD.${col(a)} IS NOT NEW.${col(a)} OR OLD.${col(b)} IS NOT NEW.${col(b)}` : `OLD.${col(a)} IS NOT NEW.${col(a)}`;
    const w = LOG_WHEN[t] || {};
    lines.push(`CREATE TRIGGER mirror_${t}_ins AFTER INSERT ON ${t} WHEN ${guard(w.ins)} BEGIN ${ins('NEW')} END;`, `CREATE TRIGGER mirror_${t}_upd AFTER UPDATE ON ${t} WHEN ${guard(w.upd)} BEGIN ${ins('NEW')} END;`,
      `CREATE TRIGGER mirror_${t}_key AFTER UPDATE ON ${t} WHEN ${guard(moved)} BEGIN ${ins('OLD')} END;`, `CREATE TRIGGER mirror_${t}_del AFTER DELETE ON ${t} WHEN ${COPY_ON} BEGIN ${ins('OLD')} END;`,
      `INSERT OR IGNORE INTO mirror_state (tbl, mode) VALUES ('${t}', 'build');`, `UPDATE mirror_state SET mode = 'build', last_id = 0, rows = 0, gen = 0, cursor = '' WHERE tbl = '${t}';`);
  }
  writeFileSync(new URL(`../worker/migrations/${outName}.sql`, import.meta.url), lines.join('\n') + '\n');
  console.log(`${outName}.sql:`, only.length, 'tables,', only.length * 4, 'triggers');
  process.exit(0);
}
// 0022 is applied; rewriting it would change an applied migration
if (!process.env.REWRITE_0022) throw new Error('usage: node setup/build-mirror-sql.mjs <NNNN_name> <table…>   (0022 is applied: set REWRITE_0022=1 only to regenerate it for reference)');

const OLD = ['accounts', 'batches', 'memberships', 'reset_requests', 'profiles', 'settings', 'attendance', 'reopens', 'class_weeks',
  'facilitators', 'announcements', 'duplicate_reviews', 'missed_weeks', 'reopen_requests'];
const col = (c) => `"${c}"`;
const lines = [
  '-- Copy to Sheets, second form (3 Oct 2026; generated by setup/build-mirror-sql.mjs — edit that, not this).',
  '-- Each insert, update or delete on a changing table appends ONE row to mirror_log (1 database write; 0018 cost about',
  '-- 3). The schedule reads the log from its position (mirror_state › mirror_log.last_id) and copies those rows; a crash',
  '-- simply re-reads. Copied entries are trimmed on quiet nights. Now also: unsent drafts, and attendance as it is',
  '-- marked (no longer only after the week locks). Rows left blank by a delete are reused (mirror_free).',
  ...OLD.flatMap((t) => ['ins', 'upd', 'key', 'del'].map((w) => `DROP TRIGGER IF EXISTS mirror_${t}_${w};`)),
  'DROP TABLE IF EXISTS mirror_changes;',
  "CREATE TABLE mirror_log (id INTEGER PRIMARY KEY, tbl TEXT NOT NULL, k1 NOT NULL, k2 NOT NULL DEFAULT '');",
  'CREATE TABLE mirror_free (tbl TEXT NOT NULL, "row" INTEGER NOT NULL, PRIMARY KEY (tbl, "row")) WITHOUT ROWID;',
  "INSERT OR IGNORE INTO mirror_state (tbl, dirty) VALUES ('mirror_log', 0);",
  "UPDATE mirror_state SET last_id = 0 WHERE tbl = 'mirror_log';"
];
for (const [t, keys] of Object.entries(KEYED)) {
  const [a, b] = keys;
  const k2 = (row) => (b ? `${row}.${col(b)}` : "''");
  const ins = (row) => `INSERT INTO mirror_log (tbl, k1, k2) VALUES ('${t}', ${row}.${col(a)}, ${k2(row)});`;
  const moved = b ? `OLD.${col(a)} IS NOT NEW.${col(a)} OR OLD.${col(b)} IS NOT NEW.${col(b)}` : `OLD.${col(a)} IS NOT NEW.${col(a)}`;
  const w = LOG_WHEN[t] || {}, when = (c) => (c ? ` WHEN ${c}` : '');
  lines.push(
    `CREATE TRIGGER mirror_${t}_ins AFTER INSERT ON ${t}${when(w.ins)} BEGIN ${ins('NEW')} END;`,
    `CREATE TRIGGER mirror_${t}_upd AFTER UPDATE ON ${t}${when(w.upd)} BEGIN ${ins('NEW')} END;`,
    `CREATE TRIGGER mirror_${t}_key AFTER UPDATE ON ${t} WHEN ${moved} BEGIN ${ins('OLD')} END;`,
    `CREATE TRIGGER mirror_${t}_del AFTER DELETE ON ${t} BEGIN ${ins('OLD')} END;`,
    `INSERT OR IGNORE INTO mirror_state (tbl) VALUES ('${t}');`
  );
}
// attendance (now copied as marked) and drafts (new) are copied whole once, over the tab, then live
lines.push("UPDATE mirror_state SET mode = 'build', last_id = 0, rows = 0, gen = 0, cursor = '' WHERE tbl IN ('attendance', 'drafts');",
  "DELETE FROM mirror_rows WHERE tbl IN ('attendance', 'drafts');");
writeFileSync(new URL('../worker/migrations/0022_mirror_log.sql', import.meta.url), lines.join('\n') + '\n');
console.log('0022_mirror_log.sql:', Object.keys(KEYED).length, 'tables,', Object.keys(KEYED).length * 4, 'triggers');
