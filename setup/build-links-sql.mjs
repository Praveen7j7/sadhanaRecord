// Writes worker/migrations/0009_links.sql: each lecture's own Drive link (data/lecture-links.json, from
// setup/match-lectures.mjs) and each book's own PDF(s) (data/book-links.json, from setup/match-books.py).
// Both lists were made read-only from the IYF Drive folders; nothing is guessed.   node setup/build-links-sql.mjs
import fs from 'node:fs';
import LECT from './data/lecture-links.json' with { type: 'json' };
import BOOKS from './data/book-links.json' with { type: 'json' };

const sq = v => (typeof v === 'number' ? String(v) : `'${String(v ?? '').replace(/'/g, "''")}'`);
/** A short name for one volume of a multi-file book. */
export function volumeLabel(name, many) {
  if (!many) return 'PDF';
  let m;
  if ((m = /^SB(\d\d)$/.exec(name))) return 'Canto ' + Number(m[1]);
  if ((m = /^\d\s+(Adi|Madhya|Antya)$/.exec(name))) return m[1] + ' Lila';
  if (/_English$/.test(name)) return 'English';
  if (/in Hindi/.test(name)) return 'Hindi';
  if ((m = /transcendental diary (\d)/i.exec(name))) return 'Volume ' + m[1];
  if ((m = /^(\d+)\s+(.+)$/.exec(name))) return `Volume ${m[1]} · ${m[2][0].toUpperCase()}${m[2].slice(1)}`;
  return name;
}
const sql = [
  "-- Each lecture's own Drive link and each book's own PDF(s) (generated by setup/build-links-sql.mjs; do not edit by hand)",
  'ALTER TABLE lectures ADD COLUMN "link" TEXT NOT NULL DEFAULT \'\';',
  'CREATE TABLE book_files ("book_id" TEXT NOT NULL REFERENCES books("book_id"), "order" INTEGER NOT NULL, "label" TEXT NOT NULL, "url" TEXT NOT NULL, PRIMARY KEY ("book_id", "order"));'
];
for (const [id, l] of Object.entries(LECT)) if (l.url) sql.push(`UPDATE lectures SET "link" = ${sq(l.url)} WHERE "lecture_id" = ${sq(id)};`);
for (const [id, files] of Object.entries(BOOKS.links)) files.forEach((f, i) =>
  sql.push(`INSERT INTO book_files ("book_id", "order", "label", "url") VALUES (${sq(id)}, ${i + 1}, ${sq(volumeLabel(f.name, files.length > 1))}, ${sq(f.url)});`));
sql.push(
  "INSERT INTO mirror_state (tbl) VALUES ('book_files');",
  "UPDATE mirror_state SET dirty = dirty + 1 WHERE tbl IN ('lectures', 'settings');",
  "UPDATE settings SET value = 'j2', changed_by = 'links' WHERE key = 'journals_version';"
);
fs.writeFileSync(new URL('../worker/migrations/0009_links.sql', import.meta.url), sql.join('\n') + '\n');
console.log(`0009_links.sql: ${Object.values(LECT).filter(l => l.url).length} lecture links, ${Object.values(BOOKS.links).flat().length} book files`);
