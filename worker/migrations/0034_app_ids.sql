-- Phase 9, item 14 (the head, 9 Oct 2026): the IYF head creates an IYF ID for a devotee who has none, in the app's own
-- series SR<yy>-0001 (never the dashboard's KT / GP / JN numbers, which the dashboard keeps handing out by itself).
-- The number is this table's own row id, so two IDs created at once can never be the same. The dashboard learns of it
-- from the head's list "Created in the app — add these to the dashboard"; the app never writes to the dashboard.
-- When the dashboard later gives the same person its own ID, the dashboard's ID wins: it is linked and the app ID is
-- kept here as RETIRED (with the ID that replaced it), for the record.
-- Copied to the Access file's AppIds tab (build it before applying this).
CREATE TABLE app_ids (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  iyf_id TEXT NOT NULL DEFAULT '',                -- SR26-0001 (set in the same batch, from id)
  login TEXT NOT NULL,                            -- the devotee it was created for
  name TEXT NOT NULL,
  batch_id TEXT NOT NULL DEFAULT '',
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  reason TEXT NOT NULL DEFAULT '',
  state TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (state IN ('ACTIVE', 'RETIRED')),
  replaced_by TEXT NOT NULL DEFAULT '',           -- the dashboard ID that replaced it
  retired_at TEXT NOT NULL DEFAULT ''
);
CREATE INDEX app_ids_by_login ON app_ids (login);
CREATE INDEX app_ids_by_id ON app_ids (iyf_id);          -- retiring one when the dashboard's ID replaces it

-- Copy to Sheets: triggers for app_ids (as generated by setup/build-mirror-sql.mjs; see 0022 for the design).
CREATE TRIGGER mirror_app_ids_ins AFTER INSERT ON app_ids BEGIN INSERT INTO mirror_log (tbl, k1, k2) VALUES ('app_ids', NEW."id", ''); END;
CREATE TRIGGER mirror_app_ids_upd AFTER UPDATE ON app_ids BEGIN INSERT INTO mirror_log (tbl, k1, k2) VALUES ('app_ids', NEW."id", ''); END;
CREATE TRIGGER mirror_app_ids_key AFTER UPDATE ON app_ids WHEN OLD."id" IS NOT NEW."id" BEGIN INSERT INTO mirror_log (tbl, k1, k2) VALUES ('app_ids', OLD."id", ''); END;
CREATE TRIGGER mirror_app_ids_del AFTER DELETE ON app_ids BEGIN INSERT INTO mirror_log (tbl, k1, k2) VALUES ('app_ids', OLD."id", ''); END;
INSERT OR IGNORE INTO mirror_state (tbl, mode) VALUES ('app_ids', 'build');
UPDATE mirror_state SET mode = 'build', last_id = 0, rows = 0, gen = 0, cursor = '' WHERE tbl = 'app_ids';
