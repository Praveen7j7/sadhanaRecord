-- Phase 0 (8 Oct 2026).
--  · sign-up from age 15 (IYF decision): under 18 is a child under the DPDP Act 2023, so the parent's or guardian's name,
--    phone and consent time are kept with the profile; and when the privacy notice was agreed to (blank: an older app).
--    Copied to Sheets as four new columns at the end of the Profiles tab (worker/src/mirror.js › SCHEMA_ADDS).
--  · the wall's moderation (the store rules): reports of a post or comment (one per person and item; the IYF head
--    dismisses them or removes the item), and whose comments a person hid for themselves (viewer = their login) or the
--    IYF head hid for everyone (viewer '*': that person's new comments are refused). Copied to the Access file's new
--    PostReports and PostMutes tabs; those tabs must exist before this is applied.
ALTER TABLE profiles ADD COLUMN parent_name TEXT NOT NULL DEFAULT '';
ALTER TABLE profiles ADD COLUMN parent_phone TEXT NOT NULL DEFAULT '';
ALTER TABLE profiles ADD COLUMN parent_consent_at TEXT NOT NULL DEFAULT '';
ALTER TABLE profiles ADD COLUMN privacy_consent_at TEXT NOT NULL DEFAULT '';

CREATE TABLE post_reports (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  ann_id INTEGER NOT NULL,
  comment_id INTEGER NOT NULL DEFAULT 0,          -- 0: the post itself
  reporter TEXT NOT NULL,
  reason TEXT NOT NULL CHECK (reason IN ('spam', 'abusive', 'inappropriate', 'other')),
  note TEXT NOT NULL DEFAULT '',
  at TEXT NOT NULL,
  state TEXT NOT NULL DEFAULT 'OPEN' CHECK (state IN ('OPEN', 'DISMISSED', 'REMOVED')),
  decided_by TEXT NOT NULL DEFAULT '',
  decided_at TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX post_reports_once ON post_reports (ann_id, comment_id, reporter);
CREATE INDEX post_reports_open ON post_reports (ann_id, comment_id) WHERE state = 'OPEN';

CREATE TABLE post_mutes (
  id INTEGER PRIMARY KEY AUTOINCREMENT,           -- the opaque key the app gets (never the person's phone)
  viewer TEXT NOT NULL,                           -- who hid the comments; '*' = the IYF head, for everyone
  author TEXT NOT NULL,                           -- whose comments are hidden
  by TEXT NOT NULL,
  at TEXT NOT NULL
);
CREATE UNIQUE INDEX post_mutes_once ON post_mutes (viewer, author);

