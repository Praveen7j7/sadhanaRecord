// Regenerates the error-code table in docs/API_REFERENCE.md from worker/src/codes.js (roadmap 3.3).
//
//   node tools/docs/codes.mjs          # rewrite the table in place
//   node tools/docs/codes.mjs --check  # exit 1 if the file is out of date (for the release gate)
//
// The table lives between the two markers below, so the rest of the document is never touched.
import fs from 'node:fs';
import { ERRORS } from '../../worker/src/codes.js';

const START = '<!-- codes:start (generated by tools/docs/codes.mjs — do not edit by hand) -->';
const END = '<!-- codes:end -->';
const RETRY = { never: 'no — the answer will not change', later: 'yes, later', fix: 'only after changing the request' };

const table = [
  '', '| Code | Means | Retrying helps? |', '|---|---|---|',
  ...Object.entries(ERRORS).map(([code, e]) => `| \`${code}\` | ${e.meaning} | ${RETRY[e.retry]} |`),
  '',
  `_${Object.keys(ERRORS).length} codes. Every reply is HTTP 200 with \`ok: false\` (see ADR 0001); the \`http\` column in`,
  '`worker/src/codes.js` is only there to say what each code would be in a status-code API._', ''
].join('\n');

const path = new URL('../../docs/API_REFERENCE.md', import.meta.url);
const text = fs.readFileSync(path, 'utf8');
const i = text.indexOf(START), j = text.indexOf(END);
if (i < 0 || j < 0) {
  console.error(`Markers not found in docs/API_REFERENCE.md. Add these two lines where the table belongs:\n${START}\n${END}`);
  process.exit(2);
}
const next = text.slice(0, i + START.length) + '\n' + table + text.slice(j);
if (process.argv.includes('--check')) {
  if (next !== text) { console.error('docs/API_REFERENCE.md error-code table is out of date — run: node tools/docs/codes.mjs'); process.exit(1); }
  console.log('error-code table is up to date');
} else if (next === text) {
  console.log('error-code table already up to date');
} else {
  fs.writeFileSync(path, next);
  console.log(`error-code table rewritten (${Object.keys(ERRORS).length} codes)`);
}
