// Lectures to the head's own Drive, step 3 (27 Oct 2026): after Code.gs has copied a journal, point the app at the copies.
// Reads the journal's lecture-links.json from its folder ("Sadhana Record lectures · <journal>", read-only, as the
// read-only SA), checks every Drive file or folder the journal's lectures link to has a copy, and writes
// worker/migrations/<n>_lectures_relink_<journal>.sql: one UPDATE per lecture, by lecture_id, that changes the row only if
// it still holds the links read here. Both columns change (the app plays `link`; `audio_url` holds the same file).
// The rollback (the same UPDATEs the other way round) is written to tools/lectures/out/. Original files stay untouched.
//   node tools/lectures/relink-sql.mjs 0076 "SPS/DPS"
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { token } from '../../setup/sa.mjs';
import { idOf } from './make-copy-script.mjs';

const [n, journal] = process.argv.slice(2);
if (!/^\d{4}$/.test(n || '') || !journal) { console.error('usage: node tools/lectures/relink-sql.mjs <migration number> <journal, e.g. "SPS/DPS">'); process.exit(1); }
const HERE = dirname(fileURLToPath(import.meta.url)), WORKER = join(HERE, '../../worker');
const api = async (path) => {
  const r = await fetch('https://www.googleapis.com/drive/v3/' + path, { headers: { authorization: 'Bearer ' + await token() } });
  if (!r.ok) throw new Error(`${r.status} ${path.split('?')[0]}`);
  return r;
};
const d1 = (sql) => JSON.parse(execFileSync('npx', ['--no-install', 'wrangler', 'd1', 'execute', 'sadhana', '--remote', '--json', '--command', sql],
  { cwd: WORKER, encoding: 'utf8', maxBuffer: 64 << 20 }))[0].results;

const dir = journal.replace(/\//g, '-'), folderName = `Sadhana Record lectures · ${dir}`;
const found = (await (await api(`files?q=${encodeURIComponent(`name = '${folderName}' and mimeType = 'application/vnd.google-apps.folder' and trashed = false`)}&fields=files(id,owners(emailAddress))`)).json()).files;
if (found.length !== 1) throw new Error(`expected one folder "${folderName}", found ${found.length}`);
const lf = (await (await api(`files?q=${encodeURIComponent(`'${found[0].id}' in parents and name = 'lecture-links.json' and trashed = false`)}&fields=files(id)`)).json()).files[0];
if (!lf) throw new Error(`lecture-links.json is not in "${folderName}" yet: run copyLectures first`);
const L = await (await api(`files/${lf.id}?alt=media`)).json();
if (L.journal !== journal || L.state !== 'done') throw new Error(`${folderName}: lecture-links.json says ${L.journal} / ${L.state}, not ${journal} / done`);
const copyOf = { ...L.files, ...L.folders };

const rows = d1(`SELECT lecture_id, audio_url, link FROM lectures WHERE journal = '${journal.replace(/'/g, "''")}' ORDER BY "order"`);
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const swap = (u, label) => {
  if (!/drive\.google\.com/.test(u || '')) return u;          // blank or not Drive: left as it is
  const id = idOf(u);
  if (!copyOf[id]) throw new Error(`${label}: no copy of ${id} (${u})`);
  return u.split(id).join(copyOf[id]);
};
const fwd = [], back = [];
let changed = 0;
for (const r of rows) {
  const a = swap(r.audio_url, r.lecture_id + ' audio_url'), l = swap(r.link, r.lecture_id + ' link');
  if (a === r.audio_url && l === r.link) continue;
  changed++;
  fwd.push(`UPDATE lectures SET audio_url = ${q(a)}, link = ${q(l)} WHERE lecture_id = ${q(r.lecture_id)} AND audio_url = ${q(r.audio_url)} AND link = ${q(r.link)};`);
  back.push(`UPDATE lectures SET audio_url = ${q(r.audio_url)}, link = ${q(r.link)} WHERE lecture_id = ${q(r.lecture_id)} AND audio_url = ${q(a)} AND link = ${q(l)};`);
}
const version = d1("SELECT value FROM settings WHERE key = 'journals_version'")[0]?.value || 'j0';
const next = 'j' + ((+version.slice(1) || 0) + 1);
const tail = (v) => [`UPDATE settings SET value = '${v}', changed_by = 'lectures relink' WHERE key = 'journals_version';`,
  `UPDATE mirror_state SET dirty = dirty + 1 WHERE tbl IN ('lectures', 'settings');`, ''];
const head = (why) => `-- ${why}. Generated by tools/lectures/relink-sql.mjs on ${new Date().toISOString().slice(0, 10)} from "${folderName}" (${L.account}).`;
const name = `${n}_lectures_relink_${dir.toLowerCase().replace(/[^a-z0-9]+/g, '_')}`;
writeFileSync(join(WORKER, 'migrations', name + '.sql'), [head(`The head, 27 Oct 2026: the ${journal} lectures (${changed} rows) now play from the head's own Drive`), ...fwd, ...tail(next)].join('\n'));
writeFileSync(join(HERE, 'out', name + '.rollback.sql'), [head(`Rollback: the ${journal} lectures back to the original files`), ...back, ...tail(version)].join('\n'));
console.log(`${changed} of ${rows.length} ${journal} lectures relinked → worker/migrations/${name}.sql (journals ${version} → ${next}); rollback in tools/lectures/out/`);
