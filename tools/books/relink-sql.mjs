// Phase 22 D1, step 3: after the head has run Code.gs (make-copy-script.mjs), point the app at the copies.
// Reads app-links.json from the "books" folder (read-only, as the read-only SA), checks every linked file has a copy,
// and writes worker/migrations/<n>_books_relink.sql. The original files stay where they are, untouched: rolling
// back is the same migration with the ids the other way round, written beside it as a .rollback.sql.
//   node tools/books/relink-sql.mjs 0069
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { token } from '../../setup/sa.mjs';
import { TARGET, idOf, linkRows } from './make-copy-script.mjs';

const n = process.argv[2];
if (!/^\d{4}$/.test(n || '')) { console.error('usage: node tools/books/relink-sql.mjs <migration number, e.g. 0069>'); process.exit(1); }
const HERE = dirname(fileURLToPath(import.meta.url));
const api = async (path) => {
  const r = await fetch('https://www.googleapis.com/drive/v3/' + path, { headers: { authorization: 'Bearer ' + await token() } });
  if (!r.ok) throw new Error(`${r.status} ${path.split('?')[0]}`);
  return r;
};
const child = async (parent, name) => (await (await api(`files?q=${encodeURIComponent(`'${parent}' in parents and name = '${name}' and trashed = false`)}&fields=files(id,mimeType)`)).json()).files[0];

const linksFile = await child(TARGET, 'app-links.json');
if (!linksFile) throw new Error('app-links.json is not in the books folder yet: run copyBooks first');
const links = await (await api(`files/${linksFile.id}?alt=media`)).json();
const english = await child(TARGET, 'English');
if (!english) throw new Error('the English folder is missing in the books folder');

const rows = linkRows(), missing = [];
for (const r of rows) if (r.t !== 'books' && !links[idOf(r.url)]) missing.push(`${r.t} ${r.book_id} ${r.label}`);
if (missing.length) throw new Error(`${missing.length} linked files have no copy yet (run copyBooks again):\n${missing.join('\n')}`);
const folders = [...new Set(rows.filter((r) => r.t === 'books').map((r) => idOf(r.url)))];
if (folders.length !== 1) throw new Error(`expected the books to share one folder link, found ${folders.length}`);

const version = JSON.parse(execFileSync('npx', ['--no-install', 'wrangler', 'd1', 'execute', 'sadhana', '--remote', '--json', '--command',
  "SELECT value FROM settings WHERE key = 'journals_version'"], { cwd: join(HERE, '../../worker'), encoding: 'utf8' }))[0].results[0]?.value || 'j0';
const next = 'j' + ((+version.slice(1) || 0) + 1);

const sql = (pairs, from, to, why) => [
  `-- Phase 22 D1 (the head, 26 Oct 2026): ${why}. Generated by tools/books/relink-sql.mjs.`,
  `UPDATE books SET "link" = replace("link", '${from}', '${to}') WHERE "link" LIKE '%${from}%';`,
  ...pairs.flatMap(([a, b]) => [
    `UPDATE book_files SET "url" = replace("url", '${a}', '${b}') WHERE "url" LIKE '%${a}%';`,
    `UPDATE book_chapters SET "url" = replace("url", '${a}', '${b}') WHERE "url" LIKE '%${a}%';`]),
  `UPDATE settings SET value = '${why.startsWith('back') ? version : next}', changed_by = 'books relink' WHERE key = 'journals_version';`,
  `UPDATE mirror_state SET dirty = dirty + 1 WHERE tbl IN ('books', 'book_files', 'book_chapters', 'settings');`, ''].join('\n');

const pairs = Object.entries(links);
const out = join(HERE, `../../worker/migrations/${n}_books_relink.sql`);
writeFileSync(out, sql(pairs, folders[0], TARGET,  // the root books folder (English + Hindi), 27 Oct
  `the app's books now open from the head's "books" folder (${pairs.length} files)`));
writeFileSync(join(HERE, `out/${n}_books_relink.rollback.sql`), sql(pairs.map(([a, b]) => [b, a]), TARGET, folders[0], 'back to the original files'));
console.log(`${pairs.length} files relinked → ${out} (journals ${version} → ${next}); rollback in tools/books/out/`);
