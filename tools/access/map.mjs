// The access map (ADR 0015 groundwork; the head, 22 Oct 2026: "define the access for all the routes"): every screen
// and every server action, who may reach it, and which screens call each action. Generated from the two sources of
// truth — the app's route table (frontend/src/routes.js) and the server's registry (worker/src/api.js) — never typed,
// so it cannot drift: worker/tests/access-map.test.mjs regenerates it and fails when docs/ACCESS_MAP.md differs.
//
//   node tools/access/map.mjs            write docs/ACCESS_MAP.md
//   node tools/access/map.mjs --check    exit 1 if the file on disk is out of date
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'docs', 'ACCESS_MAP.md');
// the mock's copy of each action's fields and whether it writes (G15): the mock then refuses an unknown field and a
// write with no request id, as the server does, instead of letting a screen's mistake pass in every browser check
const FIELDS_OUT = join(ROOT, 'frontend', 'src', 'lib', 'mockfields.js');

export async function fieldsFile() {
  // the capabilities (ADR 0015), so the mock's gate gives and takes exactly as the server's: an action list, and the
  // actions that count only when filling for somebody (onBehalfOf)
  const { CAPS, ROLES } = await import(join(ROOT, 'worker', 'src', 'grants.js'));
  const caps = CAPS.map((c) => Array.isArray(c.actions)
    ? `  { id: '${c.id}', label: ${JSON.stringify(c.label)}, give: ${!!c.give}, actions: [${c.actions.map((a) => `'${a}'`).join(', ')}], onBehalf: [] },`
    : `  { id: '${c.id}', label: ${JSON.stringify(c.label)}, give: ${!!c.give}, actions: [], onBehalf: [${Object.keys(c.actions).map((a) => `'${a}'`).join(', ')}] },`);
  const reg = readFileSync(join(ROOT, 'worker', 'src', 'api.js'), 'utf8');
  const rows = [...reg.matchAll(/^\s*'([a-zA-Z]+\.[a-zA-Z]+)':\s*\{\s*roles:\s*[A-Z]+([^\n]*)/gm)].map(([, name, rest]) => {
    const f = /fields:\s*\[([^\]]*)\]/.exec(rest)?.[1] || '';
    return `  '${name}': [${/write:\s*true/.test(rest) ? 1 : 0}, [${f.trim()}]],`;
  });
  return `// GENERATED by tools/access/map.mjs from worker/src/api.js — do not edit. Each action: [writes, fields].
// The mock (mock.js run) refuses an unknown field and a write without a request id, exactly as the server's handle().
export const FIELDS = {
${rows.join('\n')}
};
export const CAPS = [
${caps.join('\n')}
];
// the roles Access gives (ADR 0019): what each brings, and what may be added to it
export const ROLES = ${JSON.stringify(ROLES)};
`;
}

// seven people, as scopesOf(user) describes them (worker/src/db.js); the columns of both tables
export const PEOPLE = [
  ['Devotee', { devotee: { batchId: 'SPS' }, groupLeader: null, facilitator: null, trainee: null, coordinator: [], master: false }, ['DEVOTEE']],
  ['Group leader', { devotee: { batchId: 'SPS' }, groupLeader: { batchId: 'SPS' }, facilitator: null, trainee: null, coordinator: [], master: false }, ['DEVOTEE', 'LEADER']],
  ['Facilitator', { devotee: { batchId: 'SPS' }, groupLeader: null, facilitator: { name: 'F' }, trainee: null, coordinator: [], master: false }, ['DEVOTEE', 'FAC']],
  ['ETP trainee', { devotee: { batchId: 'SPS' }, groupLeader: null, facilitator: { name: 'T' }, trainee: { batchId: 'ETP-21', name: 'ETP · Batch 21' }, coordinator: [], master: false }, ['DEVOTEE', 'FAC']],
  ['Class coordinator', { devotee: null, groupLeader: null, facilitator: null, trainee: null, coordinator: ['SPS'], master: false }, ['STAFF']],
  ['Training coordinator', { devotee: null, groupLeader: null, facilitator: null, trainee: null, coordinator: ['ETP-21'], master: false }, ['STAFF']],
  ['IYF head', { devotee: null, groupLeader: null, facilitator: null, trainee: null, coordinator: [], master: true }, ['STAFF', 'MASTER']]
];
// what each registry gate admits, by the gates a person holds (the third column above); ANY is everyone signed in
const admits = (gate, held) => gate === 'PUBLIC' || gate === 'ANY' || held.includes(gate);

function files(dir) { return readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? files(p) : [p]; }); }

export async function build() {
  const { ROUTES } = await import(join(ROOT, 'frontend', 'src', 'routes.js'));
  const reg = readFileSync(join(ROOT, 'worker', 'src', 'api.js'), 'utf8');
  const actions = [...reg.matchAll(/^\s*'([a-zA-Z]+\.[a-zA-Z]+)':\s*\{\s*roles:\s*([A-Z]+)([^\n]*)/gm)]
    .map(([, name, gate, rest]) => ({ name, gate, write: /write:\s*true/.test(rest) }));
  // which screens call an action: a quoted name in src, outside the mock and the client's action lists
  const src = files(join(ROOT, 'frontend', 'src')).filter((p) => /\.(svelte|js)$/.test(p) && !/\/lib\/mock[^/]*\.js$/.test(p) && !/\/lib\/api\.js$/.test(p))
    .map((p) => [p.slice(join(ROOT, 'frontend', 'src').length + 1), readFileSync(p, 'utf8').replace(/'[a-zA-Z]+\.[a-zA-Z]+':/g, '')]);
  const callers = (a) => src.filter(([, t]) => t.includes(`'${a}'`)).map(([p]) => p.replace(/\.svelte$|\.js$/, '').split('/').pop()).sort();
  const yes = (b) => (b ? '✓' : '·');

  const head = `| ${['', ...PEOPLE.map((p) => p[0])].join(' | ')} |\n|${' --- |'.repeat(PEOPLE.length + 1)}`;
  const routeRows = ROUTES.map((r) => {
    // the pattern, said for people: a login, a week (its Monday), a date
    const path = r.re.source.replace(/^\^/, '').replace(/\$$/, '').replace(/\\\//g, '/')
      .replace(/\(?\[\^\/\]\+\)?/g, ':login').replace(/\\d\{4\}-\\d\\d-\\d\\d\/\\d\{4\}-\\d\\d-\\d\\d/g, ':week/:date')
      .replace(/\\d\{4\}-\\d\\d-\\d\\d/g, ':week').replace(/\(\/(:[a-z/:]+)\)\?/g, '[/$1]').replace(/\(home\)\?/, '[home]');
    const title = typeof r.title === 'function' ? '(per page)' : r.title || '';
    return `| \`${path}\` ${title} | ${PEOPLE.map((p) => yes((r.scope || (() => true))(p[1]))).join(' | ')} |`;
  });
  const actionRows = actions.map((a) =>
    `| \`${a.name}\`${a.write ? ' ✎' : ''} | ${a.gate} | ${PEOPLE.map((p) => yes(admits(a.gate, p[2]))).join(' | ')} | ${callers(a.name).join(', ') || (a.gate === 'PUBLIC' ? 'signed out / machines' : '—')} |`);

  return `# Access map — who reaches which screen and which action

Generated by \`node tools/access/map.mjs\` from \`frontend/src/routes.js\` and \`worker/src/api.js\`. **Do not edit by
hand:** \`worker/tests/access-map.test.mjs\` regenerates it and fails when this file differs. ✓ = allowed by the gate.

Two things a ✓ does **not** say: the server then narrows by batch or person inside the handler (a coordinator's
own batches; a facilitator's own row on a board — see \`roles.test.mjs\` HANDLER_REFUSES and \`ownership.test.mjs\`),
and a screen may hide a control the gate would allow. The server is the authority; the screen only follows it.

## Screens (${ROUTES.length})

The route's own rule (\`scope\`), evaluated for each kind of person. A person holding several roles reaches the union.

${head}
${routeRows.join('\n')}

## Server actions (${actions.length})

✎ = writes. Gate: PUBLIC (signed out too), ANY (signed in), DEVOTEE, LEADER (group leader), FAC (facilitator),
STAFF (any coordinator, or the head), MASTER (the head). "Called from" lists the screens that call it.

| Action | Gate | ${PEOPLE.map((p) => p[0]).join(' | ')} | Called from |
|${' --- |'.repeat(PEOPLE.length + 3)}
${actionRows.join('\n')}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await build(), fields = await fieldsFile();
  if (process.argv.includes('--check')) {
    let now = '', nf = ''; try { now = readFileSync(OUT, 'utf8'); nf = readFileSync(FIELDS_OUT, 'utf8'); } catch { /* missing */ }
    if (now !== text || nf !== fields) { console.error('docs/ACCESS_MAP.md or lib/mockfields.js is out of date: run node tools/access/map.mjs'); process.exit(1); }
    console.log('docs/ACCESS_MAP.md and lib/mockfields.js are up to date');
  } else { writeFileSync(OUT, text); writeFileSync(FIELDS_OUT, fields); console.log('wrote docs/ACCESS_MAP.md and frontend/src/lib/mockfields.js'); }
}
